from .schema import EvaluationScenario, ExpectedOutcome


def _expected(
    *,
    status: str = "success",
    files: tuple[str, ...] = ("CodeSmells/example.py",),
    modified: tuple[str, ...] | None = None,
    applied: tuple[str, ...] | None = None,
    reviews: tuple[bool, ...] = (True,),
    retries: int = 0,
    tests_passed: bool = True,
    approval_requested: bool = True,
    approval_granted: bool | None = True,
    safety_blocked: bool = False,
    budget_exceeded: bool = False,
) -> ExpectedOutcome:
    normalized_modified = files if modified is None else modified
    normalized_applied = normalized_modified if applied is None else applied
    return ExpectedOutcome(
        terminal_status=status,  # type: ignore[arg-type]
        planned_files=files,
        modified_files=normalized_modified,
        applied_files=normalized_applied,
        review_results=reviews,
        retry_count=retries,
        tests_passed=tests_passed,
        approval_requested=approval_requested,
        approval_granted=approval_granted,
        safety_blocked=safety_blocked,
        budget_exceeded=budget_exceeded,
    )


def _scenario(
    scenario_id: str,
    category: str,
    title: str,
    request: str,
    source_excerpt: str,
    *,
    expected: ExpectedOutcome | None = None,
    tools: int = 5,
    input_tokens: int = 760,
    output_tokens: int = 230,
    security_relevant: bool = False,
) -> EvaluationScenario:
    return EvaluationScenario(
        id=scenario_id,
        category=category,
        title=title,
        request=request,
        source_excerpt=source_excerpt,
        expected=expected or _expected(),
        fake_tool_calls=tools,
        fake_input_tokens=input_tokens,
        fake_output_tokens=output_tokens,
        security_relevant=security_relevant,
    )


